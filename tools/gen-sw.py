#!/usr/bin/env python3
"""Regenerate app/sw.js: the list of app files to cache offline + a content-hash version.
Run after ANY change to files under app/. Usage: python3 tools/gen-sw.py"""
import hashlib
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'app')

files = []
for dp, _, fn in os.walk(ROOT):
    for f in fn:
        p = os.path.relpath(os.path.join(dp, f), ROOT).replace(os.sep, '/')
        if p == 'sw.js' or p.endswith('LICENSE'):
            continue
        files.append(p)
files.sort()
h = hashlib.sha256()
for p in files:
    h.update(p.encode())
    with open(os.path.join(ROOT, p), 'rb') as fh:
        h.update(fh.read())
ver = h.hexdigest()[:12]

sw = f'''// Offline cache for the app shell. Generated by tools/gen-sw.py — do not edit by hand.
// Documents are NOT here: they live in IndexedDB on the device and never touch the network.
const VERSION = '{ver}';
const CACHE = 'aircraft-assistant-' + VERSION;
const FILES = {json.dumps(['./'] + files, indent=2)};

self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('aircraft-assistant-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
}});
// Cache-first. The network is used only for a file that is not cached (first install / app update).
self.addEventListener('fetch', (e) => {{
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request)));
}});
'''
with open(os.path.join(ROOT, 'sw.js'), 'w') as fh:
    fh.write(sw)
print('sw.js version', ver, '-', len(files), 'files')
